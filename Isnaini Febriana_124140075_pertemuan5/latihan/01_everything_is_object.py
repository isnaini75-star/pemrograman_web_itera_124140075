"""
Contoh bahwa objek di Python memiliki tipe dan dapat memiliki atribut/method.
"""

angka = 10
teks = "Belajar Python"
daftar = [1, 2, 3]

print("Tipe angka :", type(angka))
print("Tipe teks  :", type(teks))
print("Tipe daftar:", type(daftar))
print("Panjang teks:", len(teks))
print("Jumlah data:", len(daftar))
